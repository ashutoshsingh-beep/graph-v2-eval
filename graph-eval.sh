#!/usr/bin/env bash
# Graph accuracy, speed and memory: graph v2 vs the old engine (dev), scored against a SCIP oracle.
# Wraps codeparser's scripts/accuracy/scip_eval.py (method: docs/graph-v2/accuracy-method.md).
#
#   ./graph-eval.sh setup                   # every morning: fetch codeparser, pin today's engines, check tools
#   ./graph-eval.sh run <repos.tsv> [tag]   # build both engines, index, score, measure, write difference sheets
#   ./graph-eval.sh scores <out-dir>        # side-by-side table per repo
#   ./graph-eval.sh verdicts <out-dir>      # count your verdicts in the sheets
#   ./graph-eval.sh report <out-dir>        # the daily report per repo: <repo>-report.md and .json
#   ./graph-eval.sh rollup <dir>...         # lead: combine many *-report.json into rollup.md and rollup.csv
#   ./graph-eval.sh clean [days]            # delete engine builds and runs older than [days] (default 7)
#
# graph_diff.py and daily_report.py must sit next to this script.
#
# repos.tsv: one repo per line, tab separated:  name  language  url  commit
#   language is python, go or typescript (the languages with a SCIP oracle).
#
# Environment (optional):
#   KIT_HOME  default ~/graph-v2-qa
#   DEV_REF   default origin/development      (old engine; a commit SHA works too)
#   V2_REF    default origin/fleet/graph-v2   (graph v2; a commit SHA works too)
#   INTERN    your name, written into the daily report
set -euo pipefail

KIT_VERSION=5
KIT_HOME="${KIT_HOME:-$HOME/graph-v2-qa}"
CP="$KIT_HOME/codeparser"
DEV_REF="${DEV_REF:-origin/development}"
V2_REF="${V2_REF:-origin/fleet/graph-v2}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_URL="${REPO_URL:-git@github.com:Covlant/codeparser.git}"

die() { echo "error: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null || die "$1 is not installed. $2"; }
free_gb() { df -Pk "$KIT_HOME" | awk 'NR==2 {print int($4/1048576)}'; }

check_tools() {
  local bad=0 want got
  need git ""; need go ""; need node ""; need npm ""; need python3 ""; need jq "brew install jq"
  python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3,11) else 1)' || die "python 3.11 or later is needed (tomllib)"
  for pair in "scip-python:0.6.6:npm i -g @sourcegraph/scip-python@0.6.6" \
              "scip-typescript:0.4.0:npm i -g @sourcegraph/scip-typescript@0.4.0" \
              "scip-go:0.1.24:go install github.com/sourcegraph/scip-go/cmd/scip-go@v0.1.24"; do
    IFS=: read -r tool want hint <<<"$pair"
    if ! command -v "$tool" >/dev/null; then
      echo "  $tool MISSING. Install: $hint"; bad=1; continue
    fi
    got=$("$tool" --version 2>&1 | head -1)
    if [[ "$got" == *"$want"* ]]; then echo "  $tool $want ok"
    else echo "  $tool WRONG VERSION ($got); need $want. Install: $hint"; bad=1; fi
  done
  return $bad
}

case "${1:-}" in
  setup)
    mkdir -p "$KIT_HOME"
    if [ ! -d "$CP/.git" ]; then git clone "$REPO_URL" "$CP"; fi
    git -C "$CP" fetch -q origin development feat/graph-v2 fleet/graph-v2
    for f in graph_diff.py daily_report.py; do [ -f "$HERE/$f" ] || die "$f must sit next to graph-eval.sh"; done
    git -C "$CP" checkout -q --detach "$V2_REF"
    echo "kit version $KIT_VERSION"
    echo "old engine: $DEV_REF = $(git -C "$CP" rev-parse "$DEV_REF")"
    echo "graph v2:   $V2_REF = $(git -C "$CP" rev-parse "$V2_REF")"
    echo "  (the scorer, scripts/accuracy/scip_eval.py, runs from the graph v2 commit)"
    echo "  If the lead posted today's pair, run with DEV_REF=<sha> V2_REF=<sha> so everyone tests the same commits."
    echo "tools:"; check_tools || die "fix the tools above, then run setup again"
    gb=$(free_gb); echo "free disk: ${gb} GB"
    [ "$gb" -ge 20 ] || echo "  WARNING: under 20 GB free. The scorer stops a build when free disk falls below 8 GB. Run ./graph-eval.sh clean."
    ;;

  run)
    list="${2:?usage: graph-eval.sh run <repos.tsv> [tag]}"
    [ -f "$list" ] || die "no such file: $list"
    [ -d "$CP/.git" ] || die "run ./graph-eval.sh setup first"
    tag="${3:-$(date +%Y%m%d-%H%M)}"
    run="$KIT_HOME/eval/$tag"
    mkdir -p "$run"
    dev_sha=$(git -C "$CP" rev-parse "$DEV_REF"); v2_sha=$(git -C "$CP" rev-parse "$V2_REF")
    [ "$(git -C "$CP" rev-parse HEAD)" = "$v2_sha" ] || git -C "$CP" checkout -q --detach "$v2_sha"
    names=()
    {
      cat <<EOF
# generated by graph-eval.sh (kit $KIT_VERSION) on $(date -u +%Y-%m-%dT%H:%MZ)
# scorer: codeparser scripts/accuracy/scip_eval.py at $v2_sha
seed = 20261031
sample_threshold = 50000
sample_per_stratum = 1000
disagreements = 30
legacy_timeout = "45m"

[indexers]
scip-python = "0.6.6"
scip-go = "0.1.24"
scip-typescript = "0.4.0"

[engines]
v2 = "$v2_sha"
legacy = "$dev_sha"
EOF
      while IFS=$'\t' read -r name lang url commit _; do
        [[ -z "$name" || "$name" == \#* ]] && continue
        [[ "$name" =~ ^[A-Za-z0-9._-]+$ ]] || die "'$name': name may hold only letters, digits, . _ -"
        case "$lang" in python|go|typescript) ;; *) die "$name: language must be python, go or typescript, got '$lang'";; esac
        [[ "$url" =~ ^https://[^\"[:space:]]+$ ]] || die "$name: url must be https://... with no quotes or spaces"
        [[ "$commit" =~ ^[0-9a-f]{40}$ ]] || die "$name: commit must be a full 40-character SHA"
        printf '\n[[repos]]\nname = "%s"\nlanguage = "%s"\nurl = "%s"\ncommit = "%s"\n' "$name" "$lang" "$url" "$commit"
      done < "$list"
    } > "$run/manifest.toml"
    names=($(grep -E '^name = ' "$run/manifest.toml" | sed -E 's/name = "(.*)"/\1/'))
    [ ${#names[@]} -gt 0 ] || die "no repositories in $list"
    echo "manifest: $run/manifest.toml (old engine ${dev_sha:0:12}, graph v2 ${v2_sha:0:12})"
    echo "log:      $run/run.log"
    : > "$run/run.log"
    failed=0
    for name in "${names[@]}"; do
      # One repo at a time, so one failure does not stop the others.
      echo "== $name" | tee -a "$run/run.log"
      set +e
      (cd "$CP" && python3 scripts/accuracy/scip_eval.py --only "$name" \
          --manifest "$run/manifest.toml" --work "$KIT_HOME/work" --out "$run/out" --engine-repo "$CP") 2>&1 | tee -a "$run/run.log"
      rc=${PIPESTATUS[0]}
      set -e
      if [ ! -f "$run/out/$name.json" ]; then
        echo "FAILED: $name (no result, exit $rc). Read the lines above in $run/run.log." | tee -a "$run/run.log" >&2; failed=1
      elif [ "$rc" -ne 0 ]; then
        echo "CHECK FAILED: $name scored, but the scorer reports a failure (FAIL lines above: for example not deterministic). This is a finding." | tee -a "$run/run.log" >&2; failed=1
      fi
    done
    echo; echo "== difference sheets (oracle vs old engine vs graph v2)" | tee -a "$run/run.log"
    set +e
    (cd "$CP" && python3 "$HERE/graph_diff.py" --engine-repo "$CP" --manifest "$run/manifest.toml" \
        --work "$KIT_HOME/work" --out "$run/out" --history "$KIT_HOME/eval") 2>&1 | tee -a "$run/run.log"
    [ "${PIPESTATUS[0]}" -eq 0 ] || failed=1
    set -e
    echo; echo "Results in $run/out:"
    echo "  <repo>-differences.md   verify these, and fill in the Status block at the top"
    echo "  <repo>-rows.tsv         every differing call, not only the sample"
    echo "  <repo>.json, <repo>-diff.json, summary.md, <repo>-disagreements.md"
    echo "Then: ./graph-eval.sh report $run/out"
    exit $failed
    ;;

  scores)
    out="${2:?usage: graph-eval.sh scores <out-dir>}"
    need jq "brew install jq"
    found=0
    for j in "$out"/*.json; do
      case "$j" in *-diff.json|*-report.json) continue ;; esac
      [ -f "$j" ] || continue; found=1
      jq -r '"######## \(.repo) (\(.language)) @ \(.commit[0:12])   oracle: \(.oracle.tool // "scip") \(.oracle.version), \(.oracle.call_sites) call sites",
             "old engine \(.engines.legacy_commit[0:12])   graph v2 \(.engines.v2_commit[0:12])", ""' "$j"
      jq -r '
        def pct: if . == null then "n/a" elif .value == null then "n/a (n=" + ((.n // 0)|tostring) + ")" else ((.value*1000|round)/10|tostring) + "% (n=" + (.n|tostring) + ")" end;
        def pair(a;b): "\(a)\t\(b)";
        "metric\told engine (dev)\tgraph v2",
        pair("CALLS in-repo recall\t\(.legacy.calls.recall|pct)"; .v2.calls.line_level.recall|pct),
        pair("CALLS in-repo precision (line)\t\(.legacy.calls.precision|pct)"; .v2.calls.line_level.precision|pct),
        pair("CALLS precision at exact call site\t-"; .v2.calls.precision.overall|pct),
        pair("edges not scored (no oracle call on line)\t\(.legacy.calls.edges_on_lines_without_oracle_site)"; .v2.calls.line_level.edges_on_lines_without_oracle_site),
        pair("IMPORTS in-repo precision\t\(.legacy.imports.in_repo.precision|pct)"; .v2.imports.in_repo.precision|pct),
        pair("IMPORTS in-repo recall\t\(.legacy.imports.in_repo.recall|pct)"; .v2.imports.in_repo.recall|pct),
        pair("IMPORTS external precision\t\(.legacy.imports.external.precision|pct)"; .v2.imports.external.precision|pct),
        pair("IMPORTS external recall\t\(.legacy.imports.external.recall|pct)"; .v2.imports.external.recall|pct),
        pair("REFERENCES in-repo precision\t-"; .v2.references.precision.repo|pct),
        pair("REFERENCES in-repo recall\t-"; .v2.references.recall.repo|pct),
        pair("REFERENCES external precision\t-"; .v2.references.precision.external|pct),
        pair("REFERENCES external recall\t-"; .v2.references.recall.external|pct),
        pair("wall time s (run 1, run 2)\t\(.legacy.perf.wall_s|map(tostring)|join(", "))"; .v2.perf.wall_s|map(tostring)|join(", ")),
        pair("peak memory MiB (run 1, run 2)\t\(.legacy.perf.peak_rss_bytes|map(./1048576|round|tostring)|join(", "))"; .v2.perf.peak_rss_bytes|map(./1048576|round|tostring)|join(", ")),
        pair("same output on both runs\t\(.legacy.determinism.identical)"; .v2.determinism.identical)
      ' "$j" | column -t -s $'\t'
      jq -r '
        def pct: if . == null then "n/a" elif .value == null then "n/a (n=" + ((.n // 0)|tostring) + ")" else ((.value*1000|round)/10|tostring) + "% (n=" + (.n|tostring) + ")" end;
        "",
        "graph v2 line precision by tier: " + ([.v2.calls.line_level.precision.by_tier | to_entries[] | "\(.key) \(.value|pct)"] | join(", ")),
        "graph v2 files parsed \(.v2.files.parsed), failed \(.v2.files.failed)",
        "graph v2 unresolved CALLS share \(.v2.unresolved.share)",
        "  reasons: " + ([.v2.unresolved.top_unresolved_call_reasons[] | "\(.[0]) \(.[1])"] | join(", ")),
        "  ledger:  " + ([.v2.unresolved.top_ledger_kinds[] | "\(.[0]) \(.[1])"] | join(", ")),
        "graph v2 accounting (emitted = placed + ledgered, lost 0): ok=\(.v2.u12_accounting.ok) \(.v2.u12_accounting.totals)",
        "scoring mode: \(.v2.calls.mode)   (not \"all\" = scores are samples; the sheet counts will not match exactly)"
      ' "$j"
      echo
    done
    [ $found = 1 ] || die "no <repo>.json in $out"
    ;;

  verdicts)
    out="${2:?usage: graph-eval.sh verdicts <out-dir>}"
    found=0
    for f in "$out"/*-differences.md "$out"/*-disagreements.md; do
      [ -f "$f" ] || continue; found=1
      echo "== $(basename "$f")"
      # differences sheets: verdict is the 3rd column from the end; disagreement sheets: the last.
      case "$f" in *-differences.md) col=3 ;; *) col=1 ;; esac
      awk -F'|' -v col="$col" '
        /^## / { sec=$0; sub(/^## /,"",sec); sub(/ \(.*$/,"",sec) }
        /^\| *[0-9]+ *\|/ { v=$(NF-col); gsub(/^ +| +$/,"",v); v=tolower(v); if (v=="") v="(empty)"; n[sec" | "v]++ }
        END { for (k in n) printf "  %-55s %d\n", k, n[k] }' "$f" | sort
    done
    [ $found = 1 ] || die "no sheets in $out"
    ;;

  report)
    out="${2:?usage: graph-eval.sh report <out-dir>}"
    python3 "$HERE/daily_report.py" report --out "$out" --work "$KIT_HOME/work" --intern "${INTERN:-}"
    echo "Send every <repo>-report.md (to read) and <repo>-report.json (for the roll-up) from $out."
    ;;

  rollup)
    shift; [ $# -gt 0 ] || die "usage: graph-eval.sh rollup <folder with *-report.json>..."
    python3 "$HERE/daily_report.py" rollup "$@" --md rollup.md --csv rollup.csv
    ;;

  clean)
    days="${2:-7}"
    [[ "$days" =~ ^[0-9]+$ ]] || die "usage: graph-eval.sh clean [days]"
    echo "Deleting engine builds and checkouts under $KIT_HOME/work older than $days days (eval/ sheets are kept)."
    find "$KIT_HOME/work" -mindepth 1 -maxdepth 2 -type d \( -name 'v2-*' -o -name 'legacy-*' -o -name 'engine-*' \) -mtime +"$days" -print -exec rm -rf {} + 2>/dev/null || true
    echo "free disk: $(free_gb) GB"
    ;;

  *) sed -n '2,23p' "$0"; exit 2 ;;
esac
